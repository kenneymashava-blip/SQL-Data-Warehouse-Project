-- Maginitude Analysis
-- compare measure values by categories
-- measure by dimension



-- find total customers by countries
SELECT country, COUNT(customer_id) AS total_customers 
FROM gold.dim_customers
GROUP BY country
ORDER BY COUNT(customer_id) DESC

-- find total customers by gender
SELECT gender, COUNT(customer_id) AS total_customers 
FROM gold.dim_customers
GROUP BY gender
ORDER BY COUNT(customer_id) DESC

-- find total products by category
SELECT category, COUNT(product_id) AS total_products 
FROM gold.dim_products
GROUP BY category
ORDER BY COUNT(product_id) DESC

-- what is the average costs in each category
SELECT category,AVG(cost) As average_cost
FROM gold.dim_products
GROUP BY category
ORDER BY AVG(cost) DESC

-- what is the MAXIMUM cost in each category
SELECT category,MAX(cost) As average_cost
FROM gold.dim_products
GROUP BY category
ORDER BY MAX(cost) DESC

-- what is the total revenue generated by each category
SELECT dp.category,
	   SUM(fs.sales_amount) AS category_revenue
FROM gold.fact_sales as fs

LEFT JOIN gold.dim_products AS dp
ON fs.product_key = dp.product_key

GROUP BY dp.category
ORDER BY SUM(fs.sales_amount) DESC;

-- find is the total revenue generated by each customer
SELECT c.customer_key,
	   c.first_name, 
	   c.last_name,
	   SUM(f.sales_amount) AS total_revenue
FROM gold.fact_sales AS f
LEFT JOIN gold.dim_customers AS c
ON f.customer_key = c.customer_key
GROUP BY c.customer_key, c.first_name, c.last_name
ORDER BY SUM(f.sales_amount) DESC


-- What is the distribution of sold items across countries
-- QUANTITY OF ITEMS SOLD IN EACH COUNTRY

SELECT c.country,
	   SUM(f.quantity) as total_items_sold
FROM gold.fact_sales AS f
LEFT JOIN gold.dim_customers AS c
ON f.customer_key = c.customer_key
GROUP BY c.country
ORDER BY  SUM(f.quantity) desc

